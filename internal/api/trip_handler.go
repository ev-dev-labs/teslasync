package api

import (
	"net/http"
	"strconv"
	"time"

	"github.com/rs/zerolog/log"

	"github.com/ev-dev-labs/teslasync/internal/database"
	tripdb "github.com/ev-dev-labs/teslasync/internal/database/trip"
)

type TripHandler struct {
	repo *tripdb.TripRepo
}

func NewTripHandler(db *database.DB) *TripHandler {
	return &TripHandler{repo: tripdb.NewTripRepo(db)}
}

type tripSummaryResponse struct {
	ID             int64      `json:"id"`
	VehicleID      int64      `json:"vehicle_id"`
	Name           *string    `json:"name"`
	StartedAt      time.Time  `json:"started_at"`
	EndedAt        *time.Time `json:"ended_at"`
	StartDate      time.Time  `json:"start_date"`
	EndDate        *time.Time `json:"end_date"`
	CreatedByUser  *int64     `json:"created_by_user,omitempty"`
	AutoGenerated  bool       `json:"auto_generated"`
	Notes          *string    `json:"notes,omitempty"`
	TotalDistanceM float64    `json:"total_distance_m"`
	TotalEnergyWh  float64    `json:"total_energy_wh"`
	TotalDurationS int64      `json:"total_duration_s"`
	TotalCost      float64    `json:"total_cost"`
	DriveCount     int64      `json:"drive_count"`
	ChargeCount    int64      `json:"charge_count"`
	CreatedAt      time.Time  `json:"created_at"`
}

func tripSummaryDTO(in *tripdb.TripSummary) tripSummaryResponse {
	var name *string
	if in.Trip.Name != "" {
		v := in.Trip.Name
		name = &v
	}
	return tripSummaryResponse{
		ID:             in.Trip.ID,
		VehicleID:      in.Trip.VehicleID,
		Name:           name,
		StartedAt:      in.Trip.StartedAt,
		EndedAt:        in.Trip.EndedAt,
		StartDate:      in.Trip.StartedAt,
		EndDate:        in.Trip.EndedAt,
		CreatedByUser:  in.Trip.CreatedByUser,
		AutoGenerated:  in.Trip.AutoGenerated,
		Notes:          in.Trip.Notes,
		TotalDistanceM: in.TotalDistanceM,
		TotalEnergyWh:  in.TotalEnergyWh,
		TotalDurationS: in.TotalDurationS,
		TotalCost:      in.TotalCost,
		DriveCount:     in.DriveCount,
		ChargeCount:    in.ChargeCount,
		CreatedAt:      in.Trip.StartedAt,
	}
}

func tripSummaryDTOs(in []*tripdb.TripSummary) []tripSummaryResponse {
	out := make([]tripSummaryResponse, 0, len(in))
	for _, t := range in {
		out = append(out, tripSummaryDTO(t))
	}
	return out
}

func (h *TripHandler) List(w http.ResponseWriter, r *http.Request) {
	limit, offset := pagination(r)
	startTime, endTime := parseDateRange(r)
	vehicleIDStr := r.URL.Query().Get("vehicle_id")

	if vehicleIDStr != "" {
		vehicleID, err := strconv.ParseInt(vehicleIDStr, 10, 64)
		if err != nil {
			writeError(w, http.StatusBadRequest, "invalid vehicle_id")
			return
		}
		trips, err := h.repo.GetByVehicle(r.Context(), vehicleID, limit, offset, startTime, endTime)
		if err != nil {
			log.Error().Err(err).Msg("failed to get trips")
			writeError(w, http.StatusInternalServerError, "failed to get trips")
			return
		}
		if trips == nil {
			trips = make([]*tripdb.TripSummary, 0)
		}
		writeJSON(w, http.StatusOK, tripSummaryDTOs(trips))
		return
	}

	trips, err := h.repo.GetAll(r.Context(), limit, offset, startTime, endTime)
	if err != nil {
		log.Error().Err(err).Msg("failed to get trips")
		writeError(w, http.StatusInternalServerError, "failed to get trips")
		return
	}
	if trips == nil {
		trips = make([]*tripdb.TripSummary, 0)
	}
	writeJSON(w, http.StatusOK, tripSummaryDTOs(trips))
}
