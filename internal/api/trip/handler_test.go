// ---- pagination + date-range propagation ---------------------------------

func TestHandler_List_ParamPropagation(t *testing.T) {
	t.Parallel()

	// end is sent as an exclusive next-midnight instant; ParseDateRange
	// subtracts 1µs so a BETWEEN filter stays inclusive.
	startInstant := time.Date(2026, 5, 1, 0, 0, 0, 0, time.UTC)
	endInstant := time.Date(2026, 5, 10, 0, 0, 0, 0, time.UTC)
	wantEnd := endInstant.Add(-time.Microsecond)

	cases := []struct {
		name       string
		target     string
		wantAll    bool // expect GetAll (true) or GetByVehicle (false)
		wantVeh    int64
		wantLimit  int
		wantOffset int
	}{
		{
			name:       "get_all_with_paging_and_range",
			target:     "/trips?limit=25&offset=5&start=2026-05-01T00:00:00Z&end=2026-05-10T00:00:00Z",
			wantAll:    true,
			wantLimit:  25,
			wantOffset: 5,
		},
		{
			name:       "get_by_vehicle_with_paging_and_range",
			target:     "/trips?vehicle_id=42&limit=10&offset=3&start=2026-05-01T00:00:00Z&end=2026-05-10T00:00:00Z",
			wantAll:    false,
			wantVeh:    42,
			wantLimit:  10,
			wantOffset: 3,
		},
		{
			name:       "defaults_when_paging_absent",
			target:     "/trips",
			wantAll:    true,
			wantLimit:  50, // apiparams.Pagination default
			wantOffset: 0,
		},
	}

	for _, tc := range cases {
		tc := tc
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			fake := &fakeTripRepo{}
			h := newHandler(fake)

			rec := doList(h, tc.target)
			if rec.Code != http.StatusOK {
				t.Fatalf("status: got %d, want 200. body=%s", rec.Code, rec.Body.String())
			}
			if fake.gotLimit != tc.wantLimit {
				t.Errorf("limit: got %d, want %d", fake.gotLimit, tc.wantLimit)
			}
			if fake.gotOffset != tc.wantOffset {
				t.Errorf("offset: got %d, want %d", fake.gotOffset, tc.wantOffset)
			}
			if tc.wantAll {
				if fake.allCalled != 1 || fake.byVehicleCalled != 0 {
					t.Fatalf("routing: allCalled=%d byVehicleCalled=%d, want 1/0", fake.allCalled, fake.byVehicleCalled)
				}
			} else {
				if fake.byVehicleCalled != 1 || fake.allCalled != 0 {
					t.Fatalf("routing: byVehicleCalled=%d allCalled=%d, want 1/0", fake.byVehicleCalled, fake.allCalled)
				}
				if fake.gotVehicleID != tc.wantVeh {
					t.Errorf("vehicleID: got %d, want %d", fake.gotVehicleID, tc.wantVeh)
				}
			}

			// Range params only present in the first two cases.
			if strings.Contains(tc.target, "start=") {
				if !fake.gotStart.Equal(startInstant) {
					t.Errorf("start: got %v, want %v", fake.gotStart, startInstant)
				}
				if !fake.gotEnd.Equal(wantEnd) {
					t.Errorf("end: got %v, want %v (exclusive→inclusive)", fake.gotEnd, wantEnd)
				}
			} else if !fake.gotStart.IsZero() || !fake.gotEnd.IsZero() {
				t.Errorf("range must be zero when unspecified; got start=%v end=%v", fake.gotStart, fake.gotEnd)
			}
		})
	}
}

