// fakeTripRepo is an in-memory tripRepository double. It records the arguments
// each method was called with so the handler tests can assert routing (GetAll
// vs GetByVehicle) and parameter propagation (pagination + date range) without
// touching Postgres.
type fakeTripRepo struct {
	allCalled       int
	byVehicleCalled int

	gotVehicleID int64
	gotLimit     int
	gotOffset    int
	gotStart     time.Time
	gotEnd       time.Time

	out []*tripdb.TripSummary
	err error
}

func (f *fakeTripRepo) GetAll(_ context.Context, limit, offset int, startTime, endTime time.Time) ([]*tripdb.TripSummary, error) {
	f.allCalled++
	f.gotLimit, f.gotOffset, f.gotStart, f.gotEnd = limit, offset, startTime, endTime
	return f.out, f.err
}

func (f *fakeTripRepo) GetByVehicle(_ context.Context, vehicleID int64, limit, offset int, startTime, endTime time.Time) ([]*tripdb.TripSummary, error) {
	f.byVehicleCalled++
	f.gotVehicleID = vehicleID
	f.gotLimit, f.gotOffset, f.gotStart, f.gotEnd = limit, offset, startTime, endTime
	return f.out, f.err
}

func ptrString(s string) *string     { return &s }
func ptrTime(t time.Time) *time.Time { return &t }
func ptrInt64(i int64) *int64        { return &i }

func doList(h *Handler, target string) *httptest.ResponseRecorder {
	rec := httptest.NewRecorder()
	req := httptest.NewRequest(http.MethodGet, target, nil)
	h.List(rec, req)
	return rec
}

// sampleSummary is a fully-populated fixture used across the DTO assertions.
func sampleSummary(start, end time.Time) *tripdb.TripSummary {
	return &tripdb.TripSummary{
		Trip: models.Trip{
			ID:            11,
			VehicleID:     7,
			Name:          "May 2026 Summary",
			StartedAt:     start,
			EndedAt:       &end,
			CreatedByUser: ptrInt64(3),
			AutoGenerated: true,
			Notes:         ptrString("road trip"),
		},
		TotalDistanceM: 123456.0,
		TotalEnergyWh:  45000.0,
		TotalDurationS: 7200,
		DriveCount:     4,
		ChargeCount:    2,
		TotalCost:      12.34,
	}
}

// ---- routing: GetAll vs GetByVehicle -------------------------------------

func TestHandler_List_GetAll_NoVehicleFilter(t *testing.T) {
	t.Parallel()

	start := time.Date(2026, 5, 1, 8, 0, 0, 0, time.UTC)
	end := time.Date(2026, 5, 31, 18, 0, 0, 0, time.UTC)
	fake := &fakeTripRepo{out: []*tripdb.TripSummary{sampleSummary(start, end)}}
	h := newHandler(fake)

	rec := doList(h, "/trips")

	if rec.Code != http.StatusOK {
		t.Fatalf("status: got %d, want 200. body=%s", rec.Code, rec.Body.String())
	}
	if fake.allCalled != 1 {
		t.Errorf("GetAll called %d times, want 1", fake.allCalled)
	}
	if fake.byVehicleCalled != 0 {
		t.Errorf("GetByVehicle must not be called without vehicle_id; called=%d", fake.byVehicleCalled)
	}
	if ct := rec.Header().Get("Content-Type"); ct != "application/json; charset=utf-8" {
		t.Errorf("content-type: got %q", ct)
	}

	var resp []tripSummaryResponse
	if err := json.Unmarshal(rec.Body.Bytes(), &resp); err != nil {
		t.Fatalf("decode: %v", err)
	}
	if len(resp) != 1 {
		t.Fatalf("expected 1 trip, got %d", len(resp))
	}
}

