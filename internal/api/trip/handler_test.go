// ---- full DTO shape over the wire ----------------------------------------

func TestHandler_List_ResponseShape(t *testing.T) {
	t.Parallel()

	start := time.Date(2026, 5, 1, 8, 0, 0, 0, time.UTC)
	end := time.Date(2026, 5, 31, 18, 0, 0, 0, time.UTC)
	fake := &fakeTripRepo{out: []*tripdb.TripSummary{sampleSummary(start, end)}}
	h := newHandler(fake)

	rec := doList(h, "/trips?vehicle_id=7")
	if rec.Code != http.StatusOK {
		t.Fatalf("status: got %d, want 200. body=%s", rec.Code, rec.Body.String())
	}

	var resp []tripSummaryResponse
	if err := json.Unmarshal(rec.Body.Bytes(), &resp); err != nil {
		t.Fatalf("decode: %v", err)
	}
	if len(resp) != 1 {
		t.Fatalf("expected 1 trip, got %d", len(resp))
	}
	got := resp[0]

	if got.ID != 11 || got.VehicleID != 7 {
		t.Errorf("id/vehicle_id: got %d/%d, want 11/7", got.ID, got.VehicleID)
	}
	if got.Name == nil || *got.Name != "May 2026 Summary" {
		t.Errorf("name: got %v", got.Name)
	}
	// start_date and started_at are aliases of Trip.StartedAt.
	if !got.StartedAt.Equal(start) || !got.StartDate.Equal(start) {
		t.Errorf("started_at/start_date: got %v/%v, want %v", got.StartedAt, got.StartDate, start)
	}
	if got.EndedAt == nil || !got.EndedAt.Equal(end) {
		t.Errorf("ended_at: got %v, want %v", got.EndedAt, end)
	}
	if got.EndDate == nil || !got.EndDate.Equal(end) {
		t.Errorf("end_date: got %v, want %v", got.EndDate, end)
	}
	// created_at is derived from started_at (SI trips table has no audit column).
	if !got.CreatedAt.Equal(start) {
		t.Errorf("created_at must equal started_at; got %v, want %v", got.CreatedAt, start)
	}
	if got.CreatedByUser == nil || *got.CreatedByUser != 3 {
		t.Errorf("created_by_user: got %v, want 3", got.CreatedByUser)
	}
	if !got.AutoGenerated {
		t.Errorf("auto_generated: got false, want true")
	}
	if got.Notes == nil || *got.Notes != "road trip" {
		t.Errorf("notes: got %v", got.Notes)
	}
	if got.TotalDistanceM != 123456.0 {
		t.Errorf("total_distance_m: got %v, want 123456.0", got.TotalDistanceM)
	}
	if got.TotalEnergyWh != 45000.0 {
		t.Errorf("total_energy_wh: got %v, want 45000.0", got.TotalEnergyWh)
	}
	if got.TotalDurationS != 7200 {
		t.Errorf("total_duration_s: got %d, want 7200", got.TotalDurationS)
	}
	if got.TotalCost != 12.34 {
		t.Errorf("total_cost: got %v, want 12.34", got.TotalCost)
	}
	if got.DriveCount != 4 || got.ChargeCount != 2 {
		t.Errorf("counts: got drives=%d charges=%d, want 4/2", got.DriveCount, got.ChargeCount)
	}
}

