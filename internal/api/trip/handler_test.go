func TestTripSummaryDTO_DerivedAndNullableFields(t *testing.T) {
	t.Parallel()

	start := time.Date(2026, 2, 3, 4, 5, 6, 0, time.UTC)

	// In-progress trip: no end, no owner, no notes.
	in := &tripdb.TripSummary{
		Trip: models.Trip{
			ID:            5,
			VehicleID:     2,
			Name:          "In Progress",
			StartedAt:     start,
			EndedAt:       nil,
			CreatedByUser: nil,
			AutoGenerated: false,
			Notes:         nil,
		},
	}
	got := tripSummaryDTO(in)

	if !got.CreatedAt.Equal(start) || !got.StartDate.Equal(start) || !got.StartedAt.Equal(start) {
		t.Errorf("start/created aliases must all equal StartedAt; got created=%v start_date=%v started=%v",
			got.CreatedAt, got.StartDate, got.StartedAt)
	}
	if got.EndedAt != nil || got.EndDate != nil {
		t.Errorf("open trip must keep ended_at/end_date nil; got %v/%v", got.EndedAt, got.EndDate)
	}
	if got.CreatedByUser != nil {
		t.Errorf("created_by_user must pass through nil; got %v", got.CreatedByUser)
	}
	if got.Notes != nil {
		t.Errorf("notes must pass through nil; got %v", got.Notes)
	}
	if got.AutoGenerated {
		t.Errorf("auto_generated must pass through false")
	}
}

func TestTripSummaryDTOs_NilAndOrder(t *testing.T) {
	t.Parallel()

	t.Run("nil_input_returns_non_nil_empty", func(t *testing.T) {
		t.Parallel()
		out := tripSummaryDTOs(nil)
		if out == nil {
			t.Fatal("must return non-nil slice so JSON encodes as [] not null")
		}
		if len(out) != 0 {
			t.Errorf("expected empty slice, got len %d", len(out))
		}
	})

	t.Run("preserves_order", func(t *testing.T) {
		t.Parallel()
		now := time.Now().UTC()
		in := []*tripdb.TripSummary{
			{Trip: models.Trip{ID: 3, StartedAt: now}},
			{Trip: models.Trip{ID: 1, StartedAt: now}},
			{Trip: models.Trip{ID: 2, StartedAt: now}},
		}
		out := tripSummaryDTOs(in)
		if len(out) != 3 {
			t.Fatalf("expected 3, got %d", len(out))
		}
		wantIDs := []int64{3, 1, 2}
		for i, want := range wantIDs {
			if out[i].ID != want {
				t.Errorf("order[%d]: got id %d, want %d", i, out[i].ID, want)
			}
		}
	})
}

