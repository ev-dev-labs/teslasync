package models

import "time"

// Trip mirrors the forward-only SI canonical `trips` schema.
//
// The table stores only trip identity, timing, ownership, and notes. Distance,
// energy, and duration aggregates are intentionally not denormalized; handlers
// compute them from the constituent drives through trip_drives.
type Trip struct {
	ID            int64      `db:"id" json:"id"`
	VehicleID     int64      `db:"vehicle_id" json:"vehicle_id"`
	Name          string     `db:"name" json:"name"`
	StartedAt     time.Time  `db:"started_at" json:"started_at"`
	EndedAt       *time.Time `db:"ended_at" json:"ended_at,omitempty"`
	CreatedByUser *int64     `db:"created_by_user" json:"created_by_user,omitempty"`
	AutoGenerated bool       `db:"auto_generated" json:"auto_generated"`
	Notes         *string    `db:"notes" json:"notes,omitempty"`
}

// IsActive reports whether the trip is still in progress (no end timestamp).
func (t *Trip) IsActive() bool {
	return t.EndedAt == nil
}
