func TestParseRoutePaths_SortsAndDeduplicates(t *testing.T) {
	src := `
export const ROUTE_REGISTRY: readonly RouteEntry[] = [
  { path: '/vehicles/:id', name: 'VehicleDetail' },
  { path: '/', name: 'Dashboard' },
  { path: '/s/:token', name: 'SharedDrive' },
  { path: '/', name: 'DashboardDuplicate' },
];
`
	got, err := ParseRoutePaths(src)
	if err != nil {
		t.Fatalf("parse: %v", err)
	}
	want := []string{"/", "/s/:token", "/vehicles/:id"}
	if len(got) != len(want) {
		t.Fatalf("got %v, want %v", got, want)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Fatalf("got %v, want %v", got, want)
		}
	}
}

func TestParseRoutePaths_RejectsMalformedSources(t *testing.T) {
	tests := []struct {
		name string
		src  string
	}{
		{"no entries", "export const ROUTE_REGISTRY = [];"},
		{"relative path", `{ path: 'vehicles/:id' }`},
		{"query in path", `{ path: '/vehicles?x=1' }`},
		{"space in path", `{ path: '/vehicles /:id' }`},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if _, err := ParseRoutePaths(tt.src); err == nil {
				t.Fatal("expected an error")
			}
		})
	}
}

func TestRender_IsDeterministic(t *testing.T) {
	paths := []string{"/", "/s/:token"}
	first := Render(paths)
	second := Render(paths)
	if first != second {
		t.Fatal("Render is not deterministic")
	}
	if !strings.Contains(first, "Code generated by cmd/routetemplategen. DO NOT EDIT.") {
		t.Error("missing generated-code header")
	}
	if !strings.Contains(first, "package webvitals") {
		t.Error("missing package clause")
	}
	if !strings.Contains(first, `"/s/:token"`) {
		t.Error("missing route entry")
	}
	if !strings.Contains(first, "[2]string{") {
		t.Error("expected a fixed-size array so the count is compile-time checked")
	}
}

func repoRoot(t *testing.T) string {
	t.Helper()
	root, err := findModuleRoot(".")
	if err != nil {
		t.Skipf("module root not locatable from this working directory: %v", err)
	}
	return root
}

// TestFindModuleRoot proves the `go:generate` fix: the tool resolves its
// default paths against the module root, so it behaves identically whether it
// is run from the repository root or from internal/api/webvitals (which is the
// working directory `go generate` uses).
func TestFindModuleRoot(t *testing.T) {
	root := repoRoot(t)

	from := filepath.Join(root, "internal", "api", "webvitals")
	if _, err := os.Stat(from); err != nil {
		t.Skipf("package dir not present: %v", err)
	}
	got, err := findModuleRoot(from)
	if err != nil {
		t.Fatalf("findModuleRoot from package dir: %v", err)
	}
	if got != root {
		t.Fatalf("findModuleRoot(%q) = %q, want %q", from, got, root)
	}

	if _, err := findModuleRoot(t.TempDir()); err == nil {
		t.Fatal("expected an error outside any module")
	}
}

func TestResolvePath(t *testing.T) {
	root := t.TempDir()
	rel := filepath.FromSlash("web/src/lib/routeRegistry.ts")
	if got := resolvePath(root, rel); got != filepath.Join(root, rel) {
		t.Errorf("relative path not resolved against the module root: %q", got)
	}
	// An already-absolute path is honoured verbatim, whatever the root.
	abs := filepath.Join(root, "elsewhere.ts")
	if got := resolvePath(t.TempDir(), abs); got != abs {
		t.Errorf("absolute path was rewritten: %q", got)
	}
}

// TestSyntheticParamRouteBreaksTheDriftGate is the counterpart to the frontend
// freshness spec: adding a `:param` route to the canonical registry WITHOUT
// regenerating must make `--check` fail. If it did not, an opaque slug would
// reach a Prometheus label with nothing to stop it.
func TestSyntheticParamRouteBreaksTheDriftGate(t *testing.T) {
	root := repoRoot(t)

	registryPath := filepath.Join(root, "web", "src", "lib", "routeRegistry.ts")
	registry, err := os.ReadFile(registryPath)
	if err != nil {
		t.Skipf("web route registry not readable: %v", err)
	}
	generatedPath := filepath.Join(root, "internal", "api", "webvitals", "routetemplates_gen.go")
	committed, err := os.ReadFile(generatedPath)
	if err != nil {
		t.Fatalf("read generated artifact: %v", err)
	}

	// Sanity: the committed artifact is currently in sync.
	basePaths, err := ParseRoutePaths(string(registry))
	if err != nil {
		t.Fatalf("parse registry: %v", err)
	}
	if Render(basePaths) != string(committed) {
		t.Fatal("generated artifact is already stale — run `go run ./cmd/routetemplategen`")
	}

	// Inject a synthetic parameterised route the way a developer would.
	const synthetic = `  { path: '/acceptance-probe/:token', name: 'AcceptanceProbe', label: 'Acceptance Probe', i18nKey: 'routes.acceptanceProbe', hidden: true },`
	mutated := strings.Replace(
		string(registry),
		"export const ROUTE_REGISTRY: readonly RouteEntry[] = [\n",
		"export const ROUTE_REGISTRY: readonly RouteEntry[] = [\n"+synthetic+"\n",
		1,
	)
	if mutated == string(registry) {
		t.Fatal("could not inject the synthetic route — has routeRegistry.ts changed shape?")
	}

	mutatedPaths, err := ParseRoutePaths(mutated)
	if err != nil {
		t.Fatalf("parse mutated registry: %v", err)
	}
	if len(mutatedPaths) != len(basePaths)+1 {
		t.Fatalf("mutated registry has %d routes, want %d", len(mutatedPaths), len(basePaths)+1)
	}

	rendered := Render(mutatedPaths)
	if rendered == string(committed) {
		t.Fatal("drift gate would NOT fail: a new :param route produced an identical artifact")
	}
	if !strings.Contains(rendered, `"/acceptance-probe/:token"`) {
		t.Fatal("regenerated artifact is missing the new parameterised route")
	}
}

// TestCheckModeReportsStaleArtifact drives the file comparison `--check`
// performs, without shelling out.
func TestCheckModeReportsStaleArtifact(t *testing.T) {
	paths := []string{"/", "/s/:token"}
	fresh := Render(paths)
	stale := Render([]string{"/"})
	if fresh == stale {
		t.Fatal("expected different renderings")
	}

	dir := t.TempDir()
	out := filepath.Join(dir, "routetemplates_gen.go")
	if err := os.WriteFile(out, []byte(stale), 0o644); err != nil {
		t.Fatalf("write: %v", err)
	}
	existing, err := os.ReadFile(out)
	if err != nil {
		t.Fatalf("read: %v", err)
	}
	if string(existing) == fresh {
		t.Fatal("check would have passed on a stale artifact")
	}
}
