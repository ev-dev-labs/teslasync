#!/usr/bin/env node
/**
 * Route registry generator.
 *
 * Parses web/src/App.tsx and emits web/src/lib/routeRegistry.ts as a typed,
 * exhaustive list of every route. The output file is committed to source
 * control — re-run this script (and commit the diff) any time a route is
 * added, renamed, or removed in App.tsx.
 *
 * Why a generator + a committed file (not a build-time codegen)?
 * - Routes change rarely; running this on every build would be wasteful.
 * - A committed file shows up in PR diffs so reviewers see route changes.
 * - Keeps the runtime bundle deterministic and tree-shakable.
 *
 * Why freshness is enforced (`--check`):
 *   routeRegistry.ts is the SOURCE OF TRUTH for privacy-safe route templating
 *   on both the client (web/src/lib/routeTemplate.ts) and the server
 *   (internal/api/webvitals, via cmd/routetemplategen). A `:param` route added
 *   to App.tsx but never regenerated here means its opaque value — a share
 *   token, a customer slug — is NOT templated, and lands verbatim in a
 *   Prometheus label and in buffered error payloads. The chain is only as
 *   fresh as its first link, so CI runs `--check` on every push and PR.
 *
 * Run from the web/ directory:
 *   node scripts/generate-route-registry.mjs           # write
 *   node scripts/generate-route-registry.mjs --check   # verify, exit 1 on drift
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
export const APP_PATH = resolve(__dirname, '..', 'src', 'App.tsx')
export const OUT_PATH = resolve(__dirname, '..', 'src', 'lib', 'routeRegistry.ts')

// Match: <Route path="vehicles/:id" element={<SafeRoute name="VehicleDetail">…
const RE_PATH = /<Route\s+path="([^"]+)"\s+element=\{<SafeRoute\s+name="([^"]+)"/
// Match: <Route index element={<SafeRoute name="Dashboard">…
const RE_INDEX = /<Route\s+index\s+element=\{<SafeRoute\s+name="([^"]+)"/

function humanize(s) {
  // "BatteryHealth" → "Battery Health", "MQTTInspector" → "MQTT Inspector"
  return s
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1 $2')
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .trim()
}

function lowerFirst(s) {
  return s.charAt(0).toLowerCase() + s.slice(1)
}

/**
 * Parse App.tsx source into the sorted route list.
 *
 * Pure — no I/O — so the freshness gate can be unit-tested against a synthetic
 * App.tsx without touching the real tree.
 */
export function parseRoutes(src) {
  const routes = []
  const seen = new Set()

  // Fresh regex objects per call: a shared /g literal carries `lastIndex`
  // between calls and would silently skip matches on the second invocation.
  const rePath = new RegExp(RE_PATH.source, 'g')
  const reIndex = new RegExp(RE_INDEX.source, 'g')

  let m
  while ((m = rePath.exec(src)) !== null) {
    const rawPath = m[1]
    const name = m[2]
    // Skip the catch-all entry.
    if (rawPath === '*') continue
    const path = rawPath.startsWith('/') ? rawPath : '/' + rawPath
    if (seen.has(path)) continue
    seen.add(path)
    routes.push({
      path,
      name,
      label: humanize(name),
      i18nKey: 'routes.' + lowerFirst(name),
      hidden: path.includes(':') || name === 'NotFound',
    })
  }

  while ((m = reIndex.exec(src)) !== null) {
    const name = m[1]
    const path = '/'
    if (seen.has(path)) continue
    seen.add(path)
    routes.push({
      path,
      name,
      label: humanize(name),
      i18nKey: 'routes.' + lowerFirst(name),
      hidden: false,
    })
  }

  routes.sort((a, b) => a.path.localeCompare(b.path))
  return routes
}

/** Render the committed artifact. Deterministic for a given App.tsx source. */
export function buildRegistrySource(appSrc) {
  const routes = parseRoutes(appSrc)

  const header =
    `// AUTOGENERATED by web/scripts/generate-route-registry.mjs — DO NOT EDIT BY HAND.\n` +
    `// Re-run from the web/ directory:\n` +
    `//   node scripts/generate-route-registry.mjs\n` +
    `//\n` +
    `// Single source of truth for known frontend routes. Used by:\n` +
    `//   - NotFoundPage suggestion engine (closestRoutes)\n` +
    `//   - Future: command palette index, sidebar nav, tab badging\n\n`

  const body =
    `export interface RouteEntry {\n` +
    `  /** URL pathname starting with '/'. May contain :params. */\n` +
    `  path: string\n` +
    `  /** SafeRoute name attribute from App.tsx (stable id). */\n` +
    `  name: string\n` +
    `  /** Stable English label (also used as i18n fallback). */\n` +
    `  label: string\n` +
    `  /** i18n key for the human-readable label. */\n` +
    `  i18nKey: string\n` +
    `  /** Hidden from suggestion/palette UIs (parameterized or internal). */\n` +
    `  hidden?: boolean\n` +
    `}\n\n` +
    `export const ROUTE_REGISTRY: readonly RouteEntry[] = [\n` +
    routes
      .map(
        (r) =>
          `  { path: '${r.path}', name: '${r.name}', label: '${r.label.replace(/'/g, "\\'")}', i18nKey: '${r.i18nKey}'${r.hidden ? ', hidden: true' : ''} },`,
      )
      .join('\n') +
    `\n] as const\n`

  return { source: header + body, count: routes.length }
}

function parseArgs(argv) {
  const opts = { check: false, app: APP_PATH, out: OUT_PATH }
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i]
    if (arg === '--check') opts.check = true
    else if (arg === '--app') opts.app = resolve(argv[++i])
    else if (arg === '--out') opts.out = resolve(argv[++i])
    else if (arg.startsWith('--app=')) opts.app = resolve(arg.slice('--app='.length))
    else if (arg.startsWith('--out=')) opts.out = resolve(arg.slice('--out='.length))
  }
  return opts
}

function main(argv) {
  const { check, app, out } = parseArgs(argv)
  const appSrc = readFileSync(app, 'utf8')
  const { source, count } = buildRegistrySource(appSrc)

  if (check) {
    let existing = null
    try {
      existing = readFileSync(out, 'utf8')
    } catch {
      existing = null
    }
    if (existing !== source) {
      console.error(
        'generate-route-registry: src/lib/routeRegistry.ts is stale.\n' +
          '  App.tsx declares routes the committed registry does not match.\n' +
          '  Fix with:\n' +
          '    cd web && node scripts/generate-route-registry.mjs\n' +
          '    cd ..  && go run ./cmd/routetemplategen\n' +
          '  A missing :param route means its opaque value is NOT templated and\n' +
          '  will leak into Prometheus labels and buffered error payloads.',
      )
      process.exit(1)
    }
    console.log(`routeRegistry.ts up to date (${count} routes)`)
    return
  }

  writeFileSync(out, source)
  console.log(`Wrote ${count} routes to ${out}`)
}

// Run the CLI only when executed directly, so the pure helpers above can be
// imported by the freshness-gate unit test.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main(process.argv.slice(2))
}
