import { expect, test } from '@playwright/test'
import { installApiMocks, seedBrowserState, waitForHarnessReady, assertMockApiComplete } from './mockApi'

for (const theme of ['dark', 'light'] as const) {
  test(`rail fade boundaries ${theme}`, async ({ page }) => {
    await page.setViewportSize({ width: 1440, height: 800 })
    await seedBrowserState(page, theme, '/')
    const api = await installApiMocks(page, 'populated', theme)
    await page.goto('/')
    await waitForHarnessReady(page, api)
    const scroll = page.getByTestId('rail-scroll')
    const top = page.getByTestId('rail-fade-top')
    const bottom = page.getByTestId('rail-fade-bottom')
    await scroll.evaluate(element => { element.scrollTop = 0 })
    await expect(top).toHaveAttribute('data-visible', 'false')
    await expect(bottom).toHaveAttribute('data-visible', 'true')
    await scroll.evaluate(element => { element.scrollTop = 315 })
    await expect(top).toHaveAttribute('data-visible', 'true')
    await expect(bottom).toHaveAttribute('data-visible', 'true')
    for (const fade of [top, bottom]) {
      await expect(fade).toHaveCSS('opacity', '1')
      await expect(fade).toHaveCSS('z-index', '1')
      await expect(fade).toHaveCSS('pointer-events', 'none')
      expect((await fade.boundingBox())!.height).toBeGreaterThanOrEqual(40)
      const gradient = await fade.evaluate(element => getComputedStyle(element).backgroundImage)
      expect(gradient).toContain('linear-gradient')
      expect(gradient).toContain(theme === 'dark' ? 'rgb(11, 13, 18)' : 'rgb(248, 250, 252)')
    }
    await page.screenshot({ path: `../docs/sidenav-polish/${theme}-rail-fades.png`, animations: 'disabled' })
    await scroll.evaluate(element => { element.scrollTop = element.scrollHeight })
    await expect(top).toHaveAttribute('data-visible', 'true')
    await expect(bottom).toHaveAttribute('data-visible', 'false')
    await scroll.evaluate(element => { element.scrollTop = 0 })
    await expect(top).toHaveAttribute('data-visible', 'false')
    await expect(bottom).toHaveAttribute('data-visible', 'true')
    await assertMockApiComplete(page, api)
  })

  test(`panel and palette share pins ${theme}`, async ({ page }) => {
    await page.setViewportSize({ width: 1440, height: 900 })
    await seedBrowserState(page, theme, '/')
    await page.addInitScript(() => { localStorage.setItem('teslasync-pinned-nav-paths', '[]') })
    const api = await installApiMocks(page, 'populated', theme)
    await page.goto('/')
    await waitForHarnessReady(page, api)
    const rail = page.getByTestId('command-deck-rail')
    await rail.getByRole('button', { name: 'Diagnostics', exact: true }).click()
    const panel = page.getByTestId('atlas-panel-secondary')
    await expect(panel.getByRole('button', { name: 'Recent', exact: true })).toHaveCount(0)
    for (const path of ['/system-status', '/mqtt-inspector']) {
      const icon = panel.locator(`a[href="${path}"] svg`).first()
      await expect(icon).toBeVisible()
      const bounds = await icon.evaluate(element => {
        const { width, height } = (element as SVGSVGElement).getBBox()
        return { width, height }
      })
      expect(bounds.width).toBeGreaterThan(8)
      expect(bounds.height).toBeGreaterThan(8)
    }
    await panel.getByRole('button', { name: 'Pin System status to favorites', exact: true }).click()
    await expect(panel.getByRole('link', { name: 'Quick access: System status', exact: true })).toBeVisible()
    await page.screenshot({ path: `../docs/sidenav-polish/${theme}-diagnostics-panel.png`, animations: 'disabled' })
    await page.keyboard.press('Control+k')
    const dialog = page.getByRole('dialog')
    const pins = dialog.getByRole('group', { name: 'Pinned', exact: true })
    await expect(dialog.getByRole('group').first()).toHaveAttribute('aria-label', 'Pinned')
    await expect(pins.getByRole('option')).toHaveText(/System status.*\/system-status/)
    await expect(pins.locator('svg[data-nav-icon="diagnostics"]')).toBeVisible()
    await expect(dialog.getByText('No saved views yet', { exact: true })).toHaveCount(0)
    await page.screenshot({ path: `../docs/sidenav-polish/${theme}-palette-pinned.png`, animations: 'disabled' })
    await dialog.getByRole('button', { name: 'Unpin System status', exact: true }).click()
    await expect(pins).toHaveCount(0)
    await expect(dialog.getByText('Pin a page below to keep it close.', { exact: true })).toBeVisible()
    await page.screenshot({ path: `../docs/sidenav-polish/${theme}-palette-empty-pins.png`, animations: 'disabled' })
    await page.keyboard.press('Escape')
    await expect(panel.getByRole('link', { name: 'Quick access: System status', exact: true })).toHaveCount(0)
    await page.keyboard.press('Control+k')
    await dialog.getByRole('combobox').fill('MQTT inspector')
    await dialog.getByRole('option', { name: /MQTT inspector/ }).hover()
    await dialog.getByRole('button', { name: 'Pin MQTT inspector to favorites', exact: true }).click()
    await dialog.getByRole('combobox').fill('')
    await expect(pins.getByRole('option')).toHaveText(/MQTT inspector.*\/mqtt-inspector/)
    await page.keyboard.press('Escape')
    await expect(panel.getByRole('link', { name: 'Quick access: MQTT inspector', exact: true })).toBeVisible()
    await page.reload()
    await waitForHarnessReady(page, api)
    await expect(rail.getByRole('button', { name: 'Home', exact: true })).toHaveAttribute('aria-current', 'true')
    await rail.getByRole('button', { name: 'Diagnostics', exact: true }).click()
    await expect(panel.getByRole('link', { name: 'Quick access: MQTT inspector', exact: true })).toBeVisible()
    await assertMockApiComplete(page, api)
  })
}
