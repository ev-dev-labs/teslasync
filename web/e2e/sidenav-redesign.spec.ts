import { expect, test } from '@playwright/test'
import { seedBrowserState, installApiMocks, waitForHarnessReady } from './mockApi'

for (const theme of ['dark', 'light'] as const) for (const width of [375, 414, 768, 1280, 1920]) {
  test.describe(`${theme} ${width}`, () => {
  test.use({ hasTouch: width < 1280 })
  test(`${theme} ${width} navigation gallery and reload`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await seedBrowserState(page, theme, '/')
    const api = await installApiMocks(page, 'populated', theme)
    await page.goto('/')
    await waitForHarnessReady(page, api)
    const shot = (name: string) => page.screenshot({ path: `../docs/sidenav-polish/${theme}-${width}-${name}.png`, animations: 'disabled' })
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width + 1)
    if (width < 768) {
      const tabs = page.getByRole('navigation', { name: 'Quick navigation' })
      await expect(tabs.getByRole('button')).toHaveCount(5)
      await expect(page.getByRole('dialog')).toHaveCount(0)
      await shot('phone-tabs')
      await tabs.getByRole('button', { name: 'More', exact: true }).click()
      await expect(page.getByRole('dialog')).toBeVisible()
      await shot('more-sheet')
      await page.mouse.click(187, 100)
      await expect(page.getByRole('dialog')).toHaveCount(0)
      await tabs.getByRole('button', { name: 'More', exact: true }).click()
      await page.getByRole('dialog').getByRole('button', { name: 'Battery', exact: true }).click()
      await expect(page.getByRole('dialog').getByRole('searchbox')).toBeVisible()
      await shot('section-sheet')
      const dialog = page.getByRole('dialog')
      await dialog.locator('button[aria-controls]').last().click()
      const controls = dialog.locator('button:visible, input:visible, a[href]:visible')
      await controls.last().focus()
      await page.keyboard.press('Tab')
      await expect(controls.first()).toBeFocused()
      await page.keyboard.press('Shift+Tab')
      await expect(controls.last()).toBeFocused()
      await page.keyboard.press('Escape')
      await expect(page.getByRole('dialog')).toHaveCount(0)
      await page.reload(); await waitForHarnessReady(page, api)
      await expect(page.getByRole('dialog')).toHaveCount(0)
      await expect(tabs.getByRole('button', { name: 'Home', exact: true })).toHaveAttribute('aria-current', 'true')
      await tabs.getByRole('button', { name: 'Vehicles', exact: true }).click()
      await page.getByRole('dialog').locator('a[href="/vehicles"]').first().click()
      await expect(page).toHaveURL(/\/vehicles$/)
      await expect(page.getByRole('dialog')).toHaveCount(0)
      await page.reload(); await waitForHarnessReady(page, api)
      await expect(tabs.getByRole('button', { name: 'Vehicles', exact: true })).toHaveAttribute('aria-current', 'true')
      await expect(page.getByRole('dialog')).toHaveCount(0)
    } else {
      const rail = page.getByTestId('command-deck-rail')
      await expect(rail).toBeVisible()
      expect((await rail.boundingBox())!.width).toBe(76)
      if (width < 1280) {
        await rail.getByRole('button', { name: 'Home', exact: true }).click()
        await expect(page.getByRole('dialog')).toBeVisible()
        expect((await page.getByRole('dialog').boundingBox())!.x).toBe(76)
        await shot('tablet-drawer')
        await rail.getByRole('button', { name: 'Battery', exact: true }).click()
        await expect(page.getByRole('dialog').getByRole('searchbox')).toHaveAttribute('placeholder', 'Filter Battery…')
        await page.keyboard.press('Escape')
        await expect(page.getByRole('dialog')).toHaveCount(0)
        await shot('rail-collapsed')
        await rail.getByRole('button', { name: 'Battery', exact: true }).click()
        await expect(page.getByRole('dialog').getByRole('searchbox')).toHaveAttribute('placeholder', 'Filter Battery…')
        await page.mouse.click(650, 300)
        await expect(page.getByRole('dialog')).toHaveCount(0)
        await rail.getByRole('button', { name: 'Battery', exact: true }).click()
        await page.getByRole('dialog').locator('a[href="/battery"]').first().click()
        await expect(page).toHaveURL(/\/battery$/)
        await expect(page.getByRole('dialog')).toHaveCount(0)
      } else {
        const panel = page.getByTestId('command-deck-secondary')
        expect((await panel.boundingBox())!.width).toBe(272)
        await shot('panel-open')
        await rail.getByRole('button', { name: 'Battery', exact: true }).click()
        await expect(panel.getByRole('searchbox')).toHaveAttribute('placeholder', 'Filter Battery…')
        await panel.getByRole('searchbox').fill('cells')
        const matchingGroup = panel.getByRole('button', { name: 'Battery insights', exact: true })
        await matchingGroup.click()
        await expect(matchingGroup).toHaveAttribute('aria-expanded', 'false')
        await panel.getByRole('searchbox').fill('')
        await expect(panel.getByRole('button', { name: 'Battery insights', exact: true })).toHaveAttribute('aria-expanded', 'true')
        await page.reload(); await waitForHarnessReady(page, api)
        await expect(rail.getByRole('button', { name: 'Battery', exact: true })).toHaveAttribute('aria-current', 'true')
        await expect(panel.getByRole('searchbox')).toHaveAttribute('placeholder', 'Filter Battery…')
        await panel.getByRole('button', { name: 'Hide panel', exact: true }).click()
        await shot('rail-collapsed')
        await page.reload(); await waitForHarnessReady(page, api)
        await expect(panel).toHaveCount(0)
        await rail.getByRole('button', { name: 'Battery', exact: true }).click()
      }
      await page.getByTestId('rail-scroll').evaluate(element => { element.scrollTop = 300 })
      await expect(page.getByTestId('rail-fade-top')).toHaveAttribute('data-visible', 'true')
      await shot('rail-scrolled')
    }
  })
  })
}

for (const theme of ['dark', 'light'] as const) for (const width of [375, 414, 768, 1280, 1920]) {
  test.describe(`polish ${theme} ${width}`, () => {
    test.use({ hasTouch: width < 1280 })
    test('density, utilities and phone status gallery', async ({ page }) => {
      await page.setViewportSize({ width, height: 900 })
      await seedBrowserState(page, theme, '/charging')
      const api = await installApiMocks(page, 'populated', theme)
      await page.goto('/charging')
      await waitForHarnessReady(page, api)
      const shot = (name: string) => page.screenshot({ path: `../docs/sidenav-polish/${theme}-${width}-${name}.png`, animations: 'disabled' })
      if (width < 768) {
        const tabs = page.getByRole('navigation', { name: 'Quick navigation' })
        const tabBox = (await tabs.boundingBox())!
        const status = page.getByTestId('status-bar-more-trigger')
        const statusBox = (await status.boundingBox())!
        expect(statusBox.y + statusBox.height).toBeLessThanOrEqual(tabBox.y + 1)
        expect(tabBox.height).toBeGreaterThanOrEqual(56)
        const iconBox = (await tabs.getByRole('button', { name: 'Charging', exact: true }).locator('svg').boundingBox())!
        expect(iconBox.width).toBe(22)
        expect(iconBox.height).toBe(22)
        await expect(status).toHaveAccessibleName(/^Status(?:\.|$)/)
        await expect(status.locator('.lucide-activity')).toBeVisible()
        await shot('tabs-status')
        await status.click()
        await expect(page.getByRole('dialog', { name: 'Status', exact: true })).toBeVisible()
        await shot('status-expanded')
        await page.keyboard.press('Escape')
        await tabs.getByRole('button', { name: 'Charging', exact: true }).click()
        const row = page.getByRole('dialog').locator('.sidenav-page-row > a').first()
        expect((await row.boundingBox())!.height).toBeGreaterThanOrEqual(44)
        await shot('charging-section-sheet')
        await page.keyboard.press('Escape')
        await page.goto('/battery'); await waitForHarnessReady(page, api)
        await tabs.getByRole('button', { name: 'More', exact: true }).click()
        const more = page.getByRole('dialog')
        for (const title of ['Home', 'Vehicles', 'Driving', 'Charging']) await expect(more.getByRole('button', { name: title, exact: true })).toHaveCount(0)
        await expect(more.getByRole('button', { name: 'Battery', exact: true })).toHaveAttribute('aria-current', 'true')
        await shot('more-current-section')
      } else {
        if (width === 768) await page.getByTestId('command-deck-rail').getByRole('button', { name: 'Charging', exact: true }).click()
        const panel = page.getByTestId('atlas-panel-secondary')
        const row = panel.locator('.sidenav-page-row > a').first()
        const height = (await row.boundingBox())!.height
        if (width === 768) expect(height).toBeGreaterThanOrEqual(44)
        else { expect(height).toBeGreaterThanOrEqual(32); expect(height).toBeLessThanOrEqual(34) }
        await shot(width === 768 ? 'touch-drawer' : 'charging-tight-rows')
        if (width >= 1280) {
          const rail = page.getByTestId('command-deck-rail')
          const driving = rail.getByRole('button', { name: 'Driving', exact: true })
          await driving.hover()
          await expect(driving).not.toHaveAttribute('title')
          await expect(rail.locator('[data-testid="rail-scroll"] [role="tooltip"]')).toHaveCount(0)
          await shot('hover-section-no-tooltip')
          const alerts = rail.getByRole('link', { name: 'Alerts', exact: true })
          await alerts.hover()
          const tip = rail.getByRole('tooltip', { name: 'Alerts', exact: true })
          await expect(tip).toHaveCSS('opacity', '1')
          const tipBox = (await tip.boundingBox())!
          expect(tipBox.x).toBeGreaterThanOrEqual((await alerts.boundingBox())!.x + (await alerts.boundingBox())!.width)
          await shot('alerts-tooltip-right')
        }
      }
      expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width + 1)
    })
  })
}

for (const width of [768, 1280]) {
  test(`footer utilities at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await seedBrowserState(page, 'dark', '/')
    const api = await installApiMocks(page, 'populated', 'dark')
    await page.goto('/')
    await waitForHarnessReady(page, api)
    const rail = page.getByTestId('command-deck-rail')
    const trigger = rail.getByRole('button', { name: 'Open theme picker', exact: true })
    const anchor = (await trigger.boundingBox())!
    await trigger.click()
    const picker = page.getByRole('dialog', { name: 'Open theme picker', exact: true })
    await expect(picker).toBeVisible()
    await expect.poll(() => picker.locator('button').count()).toBeGreaterThan(3)
    const box = (await picker.boundingBox())!
    expect(box.height).toBeGreaterThan(200)
    expect(box.y).toBeGreaterThanOrEqual(0)
    expect(box.y + box.height).toBeLessThanOrEqual(anchor.y)
    if (width === 768) await expect(page.locator('.sidenav-tablet-panel')).toHaveCount(0)
    await page.screenshot({ path: `../docs/sidenav-polish/utilities/dark-${width}-display.png`, animations: 'disabled' })
    await page.keyboard.press('Escape')
    await expect(picker).toHaveCount(0)
    if (width === 768) await rail.getByRole('button', { name: 'Home', exact: true }).click()
    await rail.locator('summary[aria-label="Account"]').click()
    if (width === 768) await expect(page.locator('.sidenav-tablet-panel')).toHaveCount(0)
    const account = rail.locator('details[open]')
    await expect(account.locator('a[href="/account/privacy"]')).toBeVisible()
    await account.locator('a[href="/account/privacy"]').focus()
    await page.keyboard.press('Escape')
    await expect(rail.locator('details[open]')).toHaveCount(0)
    await rail.getByRole('link', { name: 'Alerts', exact: true }).click()
    await expect(page).toHaveURL(/\/notifications\/inbox$/)
  })
}
