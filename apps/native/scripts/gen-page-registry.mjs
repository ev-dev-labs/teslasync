// Generates src/web-parity-integration/pages.generated.ts:
// a static-import registry of every web-parity route page (features/ ** /pages/*.tsx
// with a default export), keyed by file basename (e.g. "AnalyticsPage").
import {readdirSync, statSync, readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import {join, relative, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const nativeRoot = join(__dirname, '..');
const pagesRoot = join(nativeRoot, 'src', 'web-parity', 'features');
const outDir = join(nativeRoot, 'src', 'web-parity-integration');
const outFile = join(outDir, 'pages.generated.ts');

function walk(dir, acc = []) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    const st = statSync(full);
    if (st.isDirectory()) walk(full, acc);
    else acc.push(full);
  }
  return acc;
}

const files = walk(pagesRoot)
  .filter((f) => /\\pages\\[^\\]+\.tsx$/.test(f) || /\/pages\/[^/]+\.tsx$/.test(f))
  .filter((f) => !f.endsWith('.parity.json'));

const entries = [];
const seen = new Map(); // basename -> path
for (const f of files) {
  const src = readFileSync(f, 'utf8');
  if (!/export\s+default/.test(src)) continue;
  const base = f.split(/[\\/]/).pop().replace(/\.tsx$/, '');
  if (seen.has(base)) {
    console.warn(`DUPLICATE basename ${base}: ${seen.get(base)} vs ${f} — keeping first`);
    continue;
  }
  seen.set(base, f);
  // import path relative to outDir, posix style, no extension
  let rel = relative(outDir, f).replace(/\\/g, '/').replace(/\.tsx$/, '');
  if (!rel.startsWith('.')) rel = './' + rel;
  entries.push({base, rel});
}

entries.sort((a, b) => a.base.localeCompare(b.base));

const header = `// AUTO-GENERATED by scripts/gen-page-registry.mjs — DO NOT EDIT BY HAND.
// Static-import registry of every web-parity route page (features/*/pages/*Page.tsx
// with a default export), keyed by file basename. Re-run: node scripts/gen-page-registry.mjs
import type {ComponentType} from 'react';
`;

const imports = entries.map((e) => `import ${e.base} from '${e.rel}';`).join('\n');
const record =
  'export const WEB_PARITY_PAGES: Record<string, ComponentType<any>> = {\n' +
  entries.map((e) => `  ${e.base},`).join('\n') +
  '\n};\n';
const count = `\nexport const WEB_PARITY_PAGE_COUNT = ${entries.length};\n`;

mkdirSync(outDir, {recursive: true});
writeFileSync(outFile, `${header}\n${imports}\n\n${record}${count}`, 'utf8');
console.log(`Wrote ${entries.length} page entries to ${outFile}`);
