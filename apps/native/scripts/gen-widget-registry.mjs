// Generates dashboardWidgets.generated.ts: a static-import registry of every
// converted dashboard widget (features/dashboard/widgets/*Widget.tsx with a
// default export), keyed by its kebab-case widget id (filename minus 'Widget').
import {readdirSync, readFileSync, writeFileSync} from 'node:fs';
import {join, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const nativeRoot = join(__dirname, '..');
const widgetsDir = join(nativeRoot, 'src', 'web-parity', 'features', 'dashboard', 'widgets');
const outFile = join(nativeRoot, 'src', 'web-parity-integration', 'dashboardWidgets.generated.ts');

function kebab(pascal) {
  return pascal
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1-$2')
    .toLowerCase();
}

const files = readdirSync(widgetsDir).filter(
  (f) => f.endsWith('Widget.tsx') && !f.endsWith('.parity.json'),
);

const entries = [];
const seen = new Set();
for (const f of files) {
  const src = readFileSync(join(widgetsDir, f), 'utf8');
  if (!/export\s+default/.test(src)) continue;
  const base = f.replace(/\.tsx$/, ''); // e.g. VehicleHeroWidget
  const id = kebab(base.replace(/Widget$/, '')); // vehicle-hero
  if (seen.has(id)) {
    console.warn(`dup id ${id} (${f}) — skipping`);
    continue;
  }
  seen.add(id);
  entries.push({ident: base, id});
}
entries.sort((a, b) => a.id.localeCompare(b.id));

const header = `// AUTO-GENERATED by scripts/gen-widget-registry.mjs — DO NOT EDIT BY HAND.
// Maps each dashboard widget id to its converted web-parity widget component.
// Re-run: node scripts/gen-widget-registry.mjs
import type {ComponentType} from 'react';
`;
const imports = entries
  .map((e) => `import ${e.ident} from '../web-parity/features/dashboard/widgets/${e.ident}';`)
  .join('\n');
const body =
  '\n// eslint-disable-next-line @typescript-eslint/no-explicit-any\n' +
  'export const DASHBOARD_WIDGET_COMPONENTS: Record<string, ComponentType<any>> = {\n' +
  entries.map((e) => `  '${e.id}': ${e.ident},`).join('\n') +
  '\n};\n\nexport const DASHBOARD_WIDGET_COUNT = ' + entries.length + ';\n';

writeFileSync(outFile, `${header}\n${imports}\n${body}`, 'utf8');
console.log(`Wrote ${entries.length} widget entries to ${outFile}`);
console.log('ids:', entries.map((e) => e.id).join(', '));
