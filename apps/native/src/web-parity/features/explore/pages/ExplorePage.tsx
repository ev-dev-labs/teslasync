/* ── Highlight match in text ────────────────────────────────────────────────── */

function escapeRegExp(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// Wraps query-token matches in a highlighted <Text> without touching markup.
function Highlight({text, query}: {text: string; query: string}) {
  const tokens = useMemo(
    () =>
      query
        .trim()
        .toLowerCase()
        .split(/\s+/)
        .filter(tok => tok.length > 0),
    [query],
  );

  const tokenSet = useMemo(() => new Set(tokens), [tokens]);

  const splitter = useMemo(() => {
    if (tokens.length === 0) {
      return null;
    }
    const escaped = tokens.map(escapeRegExp).join('|');
    return new RegExp(`(${escaped})`, 'i');
  }, [tokens]);

  if (tokens.length === 0 || !splitter) {
    return <>{text}</>;
  }

  const parts = text.split(splitter);
  return (
    <>
      {parts.map((part, i) => {
        const isMatch = tokenSet.has(part.toLowerCase());
        if (!isMatch) {
          return <Text key={i}>{part}</Text>;
        }
        return (
          <Text key={i} style={styles.mark}>
            {part}
          </Text>
        );
      })}
    </>
  );
}

/* ── Empty state ────────────────────────────────────────────────────────────── */

function EmptyResult({
  query,
  catalog,
  onPickSuggestion,
  onClear,
}: {
  query: string;
  catalog: FeatureCatalogEntry[];
  onPickSuggestion: (to: string) => void;
  onClear: () => void;
}) {
  const t = useNativeT();
  const visiblePaths = useMemo(
    () => new Set(catalog.map(c => c.to)),
    [catalog],
  );
  const suggestions = useMemo(() => {
    const fromRegistry = closestRoutes(query, ROUTE_REGISTRY, 5);
    const fromLabels = closestRoutes(
      query,
      catalog.map(c => ({
        path: c.to,
        name: c.label.replace(/\s+/g, ''),
        label: c.label,
        i18nKey: '',
      })),
      5,
    );
    const seen = new Set<string>();
    const merged: RouteSuggestion[] = [];
    for (const r of [...fromRegistry, ...fromLabels]) {
      if (!visiblePaths.has(r.path)) {
        continue;
      }
      if (seen.has(r.path)) {
        continue;
      }
      seen.add(r.path);
      merged.push(r);
    }
    merged.sort((a, b) => a.distance - b.distance);
    return merged.slice(0, 5);
  }, [query, catalog, visiblePaths]);

  return (
    <GlassPanel style={styles.emptyPanel} testID="explore-empty">
      <SemanticIcon name="search" size="md" decorative style={styles.emptyIcon} />
      <AppText variant="title" weight="semibold" style={styles.emptyTitle}>
        {t('explore.empty.title', 'No features match "{{query}}"', {query})}
      </AppText>
      <AppText tone="secondary" style={styles.emptyBody}>
        {t(
          'explore.empty.body',
          'Try a different word, or open the command palette (⌘K) to search across pages, settings, and actions.',
        )}
      </AppText>

      {suggestions.length > 0 ? (
        <View style={styles.suggestions} testID="explore-empty-suggestions">
          <AppText variant="caption" tone="muted" style={styles.suggestionsKicker}>
            {t('explore.empty.didYouMean', 'Did you mean')}
          </AppText>
          <View style={styles.suggestionList}>
            {suggestions.map(s => (
              <Pressable
                key={s.path}
                accessibilityRole="button"
                onPress={() => onPickSuggestion(s.path)}
                style={({pressed}) => [
                  styles.suggestionRow,
                  pressed && styles.pressed,
                ]}>
                <AppText>{s.label}</AppText>
                <AppText variant="caption" tone="muted">
                  {s.path}
                </AppText>
              </Pressable>
            ))}
          </View>
        </View>
      ) : null}

      <Pressable
        accessibilityRole="button"
        onPress={onClear}
        style={({pressed}) => [styles.clearButton, pressed && styles.pressed]}>
        <AppText>{t('explore.empty.clear', 'Clear filter')}</AppText>
      </Pressable>
    </GlassPanel>
  );
}

/* ── helpers ────────────────────────────────────────────────────────────────── */

function slugify(s: string): string {
  return s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');
}

