// Build the flat catalog from navSections + DESCRIPTIONS. Anything without a
// description gets a visible `Open ${label}.` fallback (test-asserted on web).
function buildFeatureCatalog(): FeatureCatalogEntry[] {
  const out: FeatureCatalogEntry[] = [];
  for (const section of navSections) {
    for (const item of section.items) {
      out.push({
        to: item.to,
        label: item.label,
        section: section.title,
        icon: SECTION_ICONS[section.title] ?? 'layoutGrid',
        description: DESCRIPTIONS[item.to] ?? `Open ${item.label}.`,
        requiresAuth: item.requiresAuth,
      });
    }
  }
  return out;
}

// Group a flat catalog by section, preserving navSections order.
function groupFeatureCatalog(
  entries: FeatureCatalogEntry[],
): {section: string; entries: FeatureCatalogEntry[]}[] {
  const order = navSections.map(s => s.title);
  const buckets = new Map<string, FeatureCatalogEntry[]>();
  for (const e of entries) {
    const bucket = buckets.get(e.section);
    if (bucket) {
      bucket.push(e);
    } else {
      buckets.set(e.section, [e]);
    }
  }
  return order
    .filter(title => buckets.has(title))
    .map(title => ({section: title, entries: buckets.get(title)!}));
}

// Case-insensitive AND-token match against label, section, description, and path.
function filterFeatureCatalog(
  entries: FeatureCatalogEntry[],
  query: string,
): FeatureCatalogEntry[] {
  const q = query.trim().toLowerCase();
  if (!q) {
    return entries;
  }
  const tokens = q.split(/\s+/);
  return entries.filter(e => {
    const haystack =
      `${e.label} ${e.section} ${e.description} ${e.to}`.toLowerCase();
    return tokens.every(tok => haystack.includes(tok));
  });
}

/* ── closestRoute (inlined from @/lib/closestRoute, pure logic) ─────────────── */

interface RouteEntry {
  path: string;
  name: string;
  label: string;
  i18nKey: string;
  hidden?: boolean;
}

interface RouteSuggestion extends RouteEntry {
  distance: number;
}

// The web combined an autogenerated ROUTE_REGISTRY (which carried hidden/internal
// routes too) with the catalog labels. Native sources the registry from
// navSections — the same data the catalog is built from (documented in sidecar).
const ROUTE_REGISTRY: readonly RouteEntry[] = navSections.flatMap(section =>
  section.items.map(item => ({
    path: item.to,
    name: item.label.replace(/\s+/g, ''),
    label: item.label,
    i18nKey: '',
  })),
);

function normalizeRoute(s: string): string {
  return s.toLowerCase().replace(/[\s\-_/]+/g, '');
}

// Iterative two-row Levenshtein. O(m*n) time, O(min(m,n)) space.
function levenshtein(a: string, b: string): number {
  if (a === b) {
    return 0;
  }
  if (!a.length) {
    return b.length;
  }
  if (!b.length) {
    return a.length;
  }
  if (a.length > b.length) {
    const tmp = a;
    a = b;
    b = tmp;
  }
  const m = a.length;
  const n = b.length;
  let prev: number[] = new Array(m + 1);
  let curr: number[] = new Array(m + 1);
  for (let i = 0; i <= m; i++) {
    prev[i] = i;
  }
  for (let j = 1; j <= n; j++) {
    curr[0] = j;
    for (let i = 1; i <= m; i++) {
      const cost = a.charCodeAt(i - 1) === b.charCodeAt(j - 1) ? 0 : 1;
      curr[i] = Math.min(curr[i - 1] + 1, prev[i] + 1, prev[i - 1] + cost);
    }
    const tmp = prev;
    prev = curr;
    curr = tmp;
  }
  return prev[m];
}

function closestRoutes(
  query: string,
  registry: readonly RouteEntry[],
  limit = 5,
): RouteSuggestion[] {
  const q = normalizeRoute(query);
  if (!q) {
    return [];
  }
  const scored: RouteSuggestion[] = [];
  for (const r of registry) {
    if (r.hidden) {
      continue;
    }
    const pathDist = levenshtein(q, normalizeRoute(r.path));
    const labelDist = levenshtein(q, normalizeRoute(r.label));
    const distance = Math.min(pathDist, labelDist);
    if (distance <= 6) {
      scored.push({...r, distance});
    }
  }
  scored.sort((a, b) => a.distance - b.distance || a.path.localeCompare(b.path));
  return scored.slice(0, limit);
}

