#!/usr/bin/env node
/*
 * gen-manifest.mjs — reconciles .github/prompts/frontend-gold-standard/logs/done.txt
 * against the generated prompt set into per-phase manifest shards plus a
 * master rollup. Generated, never hand-edited — regenerate freely after any
 * batch of completions (frontend-loop.sh calls this via self-heal-audit.mjs
 * every 25 completions, and it's safe to run manually any time).
 */
import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(__dirname, '..', '..', '..');
const PROMPTS = path.join(REPO, '.github', 'prompts', 'frontend-gold-standard');
const DONE_FILE = path.join(PROMPTS, 'logs', 'done.txt');
const MANIFEST_DIR = path.join(PROMPTS, 'manifest');

const PROGRAMS = [
  'p0-foundation', 'p1-tooling', 'p2-radix-primitives', 'p3-charts-shared',
  'p4-charts-pages', 'p5-maps-shared', 'p6-maps-pages', 'p7-storybook-stories',
  'p8-e2e-pages',
];

const done = new Set(
  fs.existsSync(DONE_FILE)
    ? fs.readFileSync(DONE_FILE, 'utf8').split('\n').map((l) => l.trim()).filter(Boolean)
    : [],
);

function commitFor(relpath) {
  // Best-effort: find the most recent commit whose message references this
  // prompt's slug (generated commits follow "type(web): <slug-derived text>").
  try {
    const slug = path.basename(relpath, '.prompt.md');
    const out = execSync(`git log --oneline --all --grep="${slug.split('-').slice(1).join(' ')}" -1`, {
      cwd: REPO, encoding: 'utf8',
    }).trim();
    return out ? out.split(' ')[0] : '';
  } catch {
    return '';
  }
}

fs.mkdirSync(MANIFEST_DIR, { recursive: true });

let grandTotal = 0;
let grandDone = 0;
const masterRows = ['| Phase | Done | Total | % |', '|---|---|---|---|'];

for (const prog of PROGRAMS) {
  const dir = path.join(PROMPTS, prog);
  const files = fs.existsSync(dir)
    ? fs.readdirSync(dir).filter((f) => f.endsWith('.prompt.md')).sort()
    : [];
  const rows = ['| unit | status | commit |', '|---|---|---|'];
  let doneCount = 0;
  for (const f of files) {
    const relpath = `${prog}/${f}`;
    const isDone = done.has(relpath);
    if (isDone) doneCount++;
    rows.push(`| ${f.replace('.prompt.md', '')} | ${isDone ? 'done' : 'pending'} | ${isDone ? commitFor(relpath) : ''} |`);
  }
  fs.writeFileSync(
    path.join(MANIFEST_DIR, `${prog}.md`),
    `# ${prog} manifest\n\n${doneCount} / ${files.length} done\n\n${rows.join('\n')}\n`,
  );
  grandTotal += files.length;
  grandDone += doneCount;
  masterRows.push(`| ${prog} | ${doneCount} | ${files.length} | ${files.length ? Math.round((100 * doneCount) / files.length) : 0}% |`);
}

masterRows.push(`| **TOTAL** | **${grandDone}** | **${grandTotal}** | **${grandTotal ? Math.round((100 * grandDone) / grandTotal) : 0}%** |`);

fs.writeFileSync(
  path.join(MANIFEST_DIR, '_master.md'),
  [
    '# Frontend Gold-Standard Rewrite — Master Manifest',
    '',
    `Generated: ${new Date().toISOString()}`,
    '',
    masterRows.join('\n'),
    '',
    '(Generated by apps/tools/frontend-rewrite/gen-manifest.mjs from logs/done.txt — never hand-edited.)',
    '',
  ].join('\n'),
);

console.log(`manifest regenerated: ${grandDone}/${grandTotal} done`);
