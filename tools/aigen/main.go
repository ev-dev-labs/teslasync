// Command aigen generates web/src/ai/features.ts from the Go feature
// registry (internal/ai/features.Registry). The Go registry is the
// single source of truth for AI feature metadata.
//
// Usage:
//
//	go run ./tools/aigen           # writes web/src/ai/features.ts
//	go run ./tools/aigen --check   # exit 1 if file would change
//
// CI invokes the --check form so a PR that adds a feature in the Go
// registry but forgets to regenerate the TS mirror is rejected at
// merge time, not at runtime.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/ev-dev-labs/teslasync/internal/ai/features"
)

const outputPath = "web/src/ai/features.ts"

// spaWiringOutputPath is the generated TS mirror of SPAWiringTable.
// Components consume the exported SPA_WIRING_BY_ID record to look
// up their endpoint path by feature ID; aivet treats imports of this
// mirror as satisfying the endpoint-reference contract.
const spaWiringOutputPath = "web/src/ai/spaWiring.ts"

func main() {
	check := flag.Bool("check", false, "exit 1 if the generated file(s) would change")
	spaWiring := flag.Bool("spa-wiring", false, "generate only the SPA wiring mirror (web/src/ai/spaWiring.ts)")
	flag.Parse()

	if err := features.CoverageOK(); err != nil {
		fmt.Fprintf(os.Stderr, "aigen: registry CoverageOK failed: %v\n", err)
		os.Exit(1)
	}
	if err := features.SPAWiringSelfCheck(); err != nil {
		fmt.Fprintf(os.Stderr, "aigen: SPAWiringSelfCheck failed: %v\n", err)
		os.Exit(1)
	}

	if *spaWiring {
		runGenerate(generateSPAWiring(), spaWiringOutputPath, *check, "SPA wiring mirror", len(features.SPAWiringTable))
		return
	}

	// Default behaviour (no flag): regenerate BOTH the features
	// mirror and the SPA wiring mirror so a developer running
	// `make generate` does not have to remember the two flags. The
	// --check form below validates both files in one pass.
	runGenerate(generate(), outputPath, *check, "features mirror", len(features.IDs()))
	runGenerate(generateSPAWiring(), spaWiringOutputPath, *check, "SPA wiring mirror", len(features.SPAWiringTable))
}

// runGenerate writes (or verifies) one of the generated artifacts.
// Pulled out of main() so the --spa-wiring path can reuse the same
// "write or compare" semantics as the default path.
func runGenerate(out []byte, relPath string, check bool, label string, count int) {
	abs, err := filepath.Abs(relPath)
	if err != nil {
		fmt.Fprintf(os.Stderr, "aigen: resolve %s: %v\n", relPath, err)
		os.Exit(1)
	}

	if check {
		existing, readErr := os.ReadFile(abs)
		if readErr != nil {
			fmt.Fprintf(os.Stderr,
				"aigen --check: %s (%s) does not exist or is unreadable: %v\n"+
					"  Run `make generate` (or `go run ./tools/aigen`) to refresh it.\n",
				relPath, label, readErr)
			os.Exit(1)
		}
		if !bytes.Equal(existing, out) {
			fmt.Fprintf(os.Stderr,
				"aigen --check: %s (%s) is stale.\n"+
					"  Regenerate with `make generate` (or `go run ./tools/aigen`).\n",
				relPath, label)
			os.Exit(1)
		}
		fmt.Printf("aigen: %s is in sync (%s, %d entries)\n", relPath, label, count)
		return
	}

	if err := os.MkdirAll(filepath.Dir(abs), 0o755); err != nil {
		fmt.Fprintf(os.Stderr, "aigen: mkdir %s: %v\n", filepath.Dir(abs), err)
		os.Exit(1)
	}
	if err := os.WriteFile(abs, out, 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "aigen: write %s: %v\n", relPath, err)
		os.Exit(1)
	}
	fmt.Printf("aigen: wrote %s (%d bytes, %s, %d entries)\n", relPath, len(out), label, count)
}

// generate builds the canonical TS source for web/src/ai/features.ts.
// Output is byte-stable across Go map iteration order (we sort by
// feature ID) so `--check` produces deterministic results.
func generate() []byte {
	ids := features.IDs()

	var b bytes.Buffer
	b.WriteString("// Code generated by tools/aigen. DO NOT EDIT.\n")
	b.WriteString("//\n")
	b.WriteString("// Source: internal/ai/features/registry.go\n")
	b.WriteString("// Regenerate with: make generate (or `go run ./tools/aigen`).\n")
	b.WriteString("//\n")
	b.WriteString("// This file is the TypeScript mirror of the Go AI feature registry.\n")
	b.WriteString("// Backend (internal/ai/features) and frontend (this file) cannot drift\n")
	b.WriteString("// because CI runs `go run ./tools/aigen --check` and fails the build\n")
	b.WriteString("// if a regeneration is required.\n")
	b.WriteString("//\n")
	b.WriteString("// Phase-50 / 0001 — F0 AI-Off Contract (ADR-015).\n")
	b.WriteString("\n")

	// AiFeatureId — typed key used by useAiEnabled / withAiFeature.
	if len(ids) == 0 {
		b.WriteString("export type AiFeatureId = never;\n\n")
	} else {
		quoted := make([]string, len(ids))
		for i, id := range ids {
			quoted[i] = fmt.Sprintf("%q", id)
		}
		fmt.Fprintf(&b, "export type AiFeatureId = %s;\n\n", strings.Join(quoted, " | "))
	}

	// AiFeatureMeta — minimal shape used by the Settings UI.
	// Larger surface fields (Routes, JobNames, …) are deliberately
	// not emitted; the off-mode walker reads them server-side from
	// the Go registry.
	b.WriteString("export interface AiFeatureMeta {\n")
	b.WriteString("  readonly id: AiFeatureId;\n")
	b.WriteString("  readonly name: string;\n")
	b.WriteString("  readonly description: string;\n")
	b.WriteString("  readonly tier: string;\n")
	b.WriteString("  readonly defaultOn: boolean;\n")
	b.WriteString("  readonly needsRag: boolean;\n")
	b.WriteString("  readonly needsTools: boolean;\n")
	b.WriteString("  readonly needsStream: boolean;\n")
	b.WriteString("  readonly uiTestIds: readonly string[];\n")
	b.WriteString("}\n\n")

	// AI_FEATURES — the canonical map, keyed by AiFeatureId so a
	// typo at the call site is a tsc error rather than a silent
	// `undefined` lookup.
	b.WriteString("export const AI_FEATURES: Readonly<Record<AiFeatureId, AiFeatureMeta>> = Object.freeze({\n")
	for _, id := range ids {
		f, _ := features.Get(id)
		fmt.Fprintf(&b, "  %q: Object.freeze({\n", id)
		fmt.Fprintf(&b, "    id: %q,\n", f.ID)
		fmt.Fprintf(&b, "    name: %q,\n", f.Name)
		fmt.Fprintf(&b, "    description: %q,\n", f.Description)
		fmt.Fprintf(&b, "    tier: %q,\n", f.Tier)
		fmt.Fprintf(&b, "    defaultOn: %t,\n", f.DefaultOn)
		fmt.Fprintf(&b, "    needsRag: %t,\n", f.NeedsRAG)
		fmt.Fprintf(&b, "    needsTools: %t,\n", f.NeedsTools)
		fmt.Fprintf(&b, "    needsStream: %t,\n", f.NeedsStream)
		b.WriteString("    uiTestIds: Object.freeze([")
		for i, tid := range f.Routes.UITestIDs {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%q", tid)
		}
		b.WriteString("] as const),\n")
		b.WriteString("  }),\n")
	}
	b.WriteString("});\n\n")

	// AI_FEATURE_IDS — the deterministic list, useful for the
	// off-mode invariant test which iterates every known feature.
	b.WriteString("export const AI_FEATURE_IDS: readonly AiFeatureId[] = Object.freeze([\n")
	for _, id := range ids {
		fmt.Fprintf(&b, "  %q,\n", id)
	}
	b.WriteString("] as const);\n\n")

	// isKnownAiFeature — type-guard mirror of features.IsKnown.
	b.WriteString("export function isKnownAiFeature(id: string): id is AiFeatureId {\n")
	b.WriteString("  return Object.prototype.hasOwnProperty.call(AI_FEATURES, id);\n")
	b.WriteString("}\n")

	return b.Bytes()
}

// generateSPAWiring emits web/src/ai/spaWiring.ts — the typed mirror
// of features.SPAWiringTable. SPA components consume
// SPA_WIRING_BY_ID[<feature-id>].endpointPath when they would
// otherwise hand-write the path string in useAiStream's `url` field;
// using the mirror keeps the URL in lock-step with Go and satisfies
// aivet's endpoint-reference rule.
func generateSPAWiring() []byte {
	table := features.SPAWiringTable

	var b bytes.Buffer
	b.WriteString("// Code generated by tools/aigen --spa-wiring. DO NOT EDIT.\n")
	b.WriteString("//\n")
	b.WriteString("// Source: internal/ai/features/spa_wiring.go\n")
	b.WriteString("// Regenerate with: make generate (or `go run ./tools/aigen`).\n")
	b.WriteString("//\n")
	b.WriteString("// This file is the TypeScript mirror of the Go SPAWiringTable.\n")
	b.WriteString("// Backend (internal/ai/features) and frontend (this file) cannot\n")
	b.WriteString("// drift because CI runs `go run ./tools/aigen --check` and fails\n")
	b.WriteString("// the build if a regeneration is required.\n")
	b.WriteString("//\n")
	b.WriteString("// Phase-50 / 0065 W1 — SPA AI feature wiring completion.\n")
	b.WriteString("\n")

	b.WriteString("import type { AiFeatureId } from './features';\n\n")

	b.WriteString("export type RenderContract = 'narrative' | 'proposal' | 'suggestion';\n\n")

	b.WriteString("export interface SPAWiringEntry {\n")
	b.WriteString("  readonly featureId: AiFeatureId;\n")
	b.WriteString("  /** Path under web/src/ to the component file that owns the wiring. */\n")
	b.WriteString("  readonly component: string;\n")
	b.WriteString("  /** Canonical Registry.Backend[0], e.g. \"POST /api/v1/ai/chatbot\". */\n")
	b.WriteString("  readonly endpoint: string;\n")
	b.WriteString("  /** Path after /api/v1, ready to pass to useAiStream({ url }). */\n")
	b.WriteString("  readonly endpointPath: string;\n")
	b.WriteString("  /** HTTP method, e.g. \"POST\". */\n")
	b.WriteString("  readonly method: string;\n")
	b.WriteString("  readonly render: RenderContract;\n")
	b.WriteString("  /** Empty for narrative entries; SPA route path for proposal/suggestion. */\n")
	b.WriteString("  readonly baselineFormHandoff: string;\n")
	b.WriteString("}\n\n")

	b.WriteString("export const SPA_WIRING: ReadonlyArray<SPAWiringEntry> = Object.freeze([\n")
	for _, w := range table {
		fmt.Fprintf(&b, "  Object.freeze({\n")
		fmt.Fprintf(&b, "    featureId: %q,\n", w.FeatureID)
		fmt.Fprintf(&b, "    component: %q,\n", w.Component)
		fmt.Fprintf(&b, "    endpoint: %q,\n", w.Endpoint)
		fmt.Fprintf(&b, "    endpointPath: %q,\n", features.SPAWiringEndpointPath(w.Endpoint))
		fmt.Fprintf(&b, "    method: %q,\n", features.SPAWiringEndpointMethod(w.Endpoint))
		fmt.Fprintf(&b, "    render: %q,\n", string(w.Render))
		fmt.Fprintf(&b, "    baselineFormHandoff: %q,\n", w.BaselineFormHandoff)
		fmt.Fprintf(&b, "  }),\n")
	}
	b.WriteString("] as const);\n\n")

	b.WriteString("export const SPA_WIRING_BY_ID: Readonly<Record<AiFeatureId, SPAWiringEntry>> = Object.freeze({\n")
	for _, w := range table {
		fmt.Fprintf(&b, "  %q: Object.freeze({\n", w.FeatureID)
		fmt.Fprintf(&b, "    featureId: %q,\n", w.FeatureID)
		fmt.Fprintf(&b, "    component: %q,\n", w.Component)
		fmt.Fprintf(&b, "    endpoint: %q,\n", w.Endpoint)
		fmt.Fprintf(&b, "    endpointPath: %q,\n", features.SPAWiringEndpointPath(w.Endpoint))
		fmt.Fprintf(&b, "    method: %q,\n", features.SPAWiringEndpointMethod(w.Endpoint))
		fmt.Fprintf(&b, "    render: %q,\n", string(w.Render))
		fmt.Fprintf(&b, "    baselineFormHandoff: %q,\n", w.BaselineFormHandoff)
		fmt.Fprintf(&b, "  }),\n")
	}
	b.WriteString("}) as Readonly<Record<AiFeatureId, SPAWiringEntry>>;\n")

	return b.Bytes()
}
